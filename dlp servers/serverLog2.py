    def do_GET(self):
        parsed = urlparse(self.path)
        params = parse_qs(parsed.query)
        
        if 'url' not in params:
            self.send_response(400)
            self.end_headers()
            return
        
        yt_url = params['url'][0]
        print(f"resolving: {yt_url}")
        
        start = time.time()
        try:
            result = subprocess.run([
                r'C:\Users\karas\Desktop\папка под гошник\yt-dlp.exe',
                '--js-runtimes', r'node:C:\Program Files\nodejs\node.exe',
                '--remote-components', 'ejs:github',
                '--cookies', cookies,
                '-f', 'bestaudio/best',
                '--get-url',
                yt_url
            ], capture_output=True, text=True, timeout=30)
            
            audio_url = result.stdout.strip()
            elapsed = time.time() - start
            print(f"resolved in {elapsed:.2f}s")
            print(f"stdout: '{audio_url}'")
            print(f"stderr: '{result.stderr}'")
            
            if not audio_url:
                print(f"error: {result.stderr}")
                self.send_response(500)
                self.end_headers()
                self.wfile.write(result.stderr.encode())
                return
                
            self.send_response(200)
            self.send_header('Content-Type', 'application/json')
            self.end_headers()
            self.wfile.write(json.dumps({'url': audio_url, 'duration': 0}).encode())
            
        except Exception as e:
            print(f"error: {e}")
            self.send_response(500)
            self.end_headers()
            self.wfile.write(str(e).encode())
            
