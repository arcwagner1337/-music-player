class Handler(BaseHTTPRequestHandler):

    def convert_firefox_cookies(db_path, output_path):
    # Подключаемся к базе данных
        conn = sqlite3.connect(db_path)
        cursor = conn.cursor()

        # Запрос данных из таблицы moz_cookies
        cursor.execute("SELECT host, isHttpOnly, path, isSecure, expiry, name, value FROM moz_cookies")
        rows = cursor.fetchall()

        with open(output_path, 'w', encoding='utf-8', newline='\n') as f:
            # Заголовок, который ожидает yt-dlp
            f.write("# Netscape HTTP Cookie File\n")
            f.write("# This file is generated by yt-dlp.  Do not edit.\n\n")

            for row in rows:
                host, isHttpOnly, path, isSecure, expiry, name, value = row

                # Преобразование логических значений в TRUE/FALSE
                include_subdomains = "TRUE" if host.startswith(".") else "FALSE"
                secure = "TRUE" if isSecure else "FALSE"

                # Запись строки в формате Netscape
                # Host | IncludeSubdomains | Path | Secure | Expiry | Name | Value
                f.write(f"{host}\t{include_subdomains}\t{path}\t{secure}\t{expiry}\t{name}\t{value}\n")

        conn.close()
        print(f"Готово! Файл сохранен в: {output_path}")


